<#
.SYNOPSIS
  Regenerates db/seed.sql (the starting data of a brand-new DiagnosticLabsV2 database) from a reference database.

.DESCRIPTION
  Reads the menu (ModuleTypes, Modules), the services the lab forms hang off, the reference ranges
  (ModuleDefaults for Hematology, Clinical Chemistry, Physical Examination, Clinical Microscopy) and the
  Patients dropdown values from a database that has the current schema, and writes them as one SQL script.
  Nothing is written to the source database. Run again after adding a module or changing a reference range.

  What is deliberately NOT copied: patients, registrations, results, users, prices (new services start at 0),
  test defaults (e.g. the Stool/Fecalysis "QQQ" defaults) and client-specific names (signatories).

.EXAMPLE
  .\Generate-Seed.ps1 -Server "DDDAVID\MSSQLSERVER01"
#>
[CmdletBinding()]
param(
    [string]$Server = 'localhost',
    [string]$Database = 'DiagnosticLabsV2',
    [string]$Output
)

$ErrorActionPreference = 'Stop'
if (-not $Output) { $Output = Join-Path $PSScriptRoot '..\db\seed.sql' }
Add-Type -AssemblyName System.Data

# Modules whose normal-range / reference defaults are product data, not test data.
$defaultsModules = 7, 11, 29, 30
# Modules from this id up are the forms a lab made in the Custom Lab Form screen (ModuleIds.FirstCustomForm): they belong to that lab and are never part of the starting data.
$firstCustomForm = 1000
# Menu entries kept inactive (the unbuilt "Medical Examination" screens, and Annual Physical Exam Page 2, now a tab of the Annual Physical Exam);
# their services are inactive too (Page 2 has none any more: the MergeAnnualPhysicalExamPage2 migration deleted it).
$inactiveModules = 14, 15, 17

$conn = New-Object System.Data.SqlClient.SqlConnection "Server=$Server;Database=$Database;Integrated Security=True;TrustServerCertificate=True;ApplicationIntent=ReadOnly"
$conn.Open()

function Get-Rows([string]$sql) {
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $sql
    $t = New-Object System.Data.DataTable
    [void](New-Object System.Data.SqlClient.SqlDataAdapter $cmd).Fill($t)
    , $t.Rows
}
function Sql($v) {
    if ($v -is [System.DBNull] -or $null -eq $v) { return 'NULL' }
    if ($v -is [bool]) { return [int]$v }
    if ($v -is [string]) { return "N'" + $v.Replace("'", "''") + "'" }
    return [string]$v
}

$types    = Get-Rows 'SELECT Id,ModuleTypeName,Icon,SortOrder,IsActive,IsAdmin FROM ModuleTypes ORDER BY Id'
$modules  = Get-Rows "SELECT Id,ModuleTypeId,ModuleName,HasView,HasCreate,HasEdit,HasDelete,HasSearch,HasPrint,HasShowList,HasSetDefaults,Icon,SortOrder,IsActive,ServiceId FROM Modules WHERE Id < $firstCustomForm ORDER BY Id"
$services = Get-Rows "SELECT DISTINCT s.Id,s.ServiceName,s.ServiceDescription FROM Services s JOIN Modules m ON m.ServiceId = s.Id WHERE m.Id < $firstCustomForm ORDER BY s.Id"
$defaults = Get-Rows ("SELECT ModuleId,Defaults FROM ModuleDefaults WHERE ModuleId IN (" + ($defaultsModules -join ',') + ") ORDER BY ModuleId")
$lookups  = Get-Rows "SELECT ModuleId,Kind,FieldName,Title,Value FROM LookupValues WHERE ModuleId IS NULL AND Kind = 2 AND FieldName IN (N'Gender',N'Civil Status') ORDER BY Id"
$conn.Dispose()

$sb = New-Object System.Text.StringBuilder
function Add([string]$line = '') { [void]$sb.AppendLine($line) }

Add @'
/*
  Starting data for a NEW DiagnosticLabsV2 database. GENERATED by tools/Generate-Seed.ps1 - do not edit by hand.

  Run once, right after db/schema.sql, on an EMPTY database. Everything runs in one transaction.

    $env:DL_ADMIN_PASSWORD = '<temporary password>'      # letters/digits, 8+ characters, no quotes
    sqlcmd -S <server> -d DiagnosticLabsV2 -E -C -I -b -i db/seed.sql

  Creates
   * the menu: module types and modules, with the lab forms linked to their services
   * the services behind the lab forms (price 0: the lab sets prices on the Services screen)
   * reference ranges for Hematology, Clinical Chemistry, Physical Examination and Clinical Microscopy
   * the Patients dropdown values (Gender, Civil Status)
   * the Admin user, who must change the temporary password at the first sign-in

  Does NOT create companies, departments, items, discounts, packages or any other lab-specific lists:
  they are entered in the app. Administrators see every screen, so no permission rows are needed.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

IF EXISTS (SELECT 1 FROM [Users]) OR EXISTS (SELECT 1 FROM [Modules]) OR EXISTS (SELECT 1 FROM [Services])
    THROW 50000, 'Target database is not empty. Run this once, on a fresh database created from db/schema.sql.', 1;

DECLARE @pwd nvarchar(200) = N'$(DL_ADMIN_PASSWORD)';
IF @pwd IS NULL OR LEN(@pwd) < 8 OR @pwd LIKE NCHAR(36) + N'(%' OR @pwd LIKE N'%[^ -~]%' COLLATE Latin1_General_BIN
    THROW 50001, 'Set DL_ADMIN_PASSWORD (8+ plain ASCII characters) before running this script.', 1;

BEGIN TRANSACTION;

-- Admin. The app accepts this SHA-1 form once, then stores a salted PBKDF2 hash at the first sign-in.
INSERT INTO [Users] ([Username], [FullName], [PasswordHash], [IsAdmin], [MustChangePassword], [FailedLoginCount], [IsActive])
VALUES (N'Admin', N'Administrator', CONVERT(varchar(40), HASHBYTES('SHA1', CAST(@pwd AS varchar(200))), 2), 1, 1, 0, 1);

'@

function Tuple([object[]]$vals) {
    '  (' + (($vals | ForEach-Object { Sql $_ }) -join ', ') + ')'
}
function Join-Rows($tuples) { ($tuples -join ",`r`n") }

Add 'INSERT INTO [ModuleTypes] ([Id], [ModuleTypeName], [Icon], [SortOrder], [IsActive], [IsAdmin]) VALUES'
Add (Join-Rows ($types | ForEach-Object { Tuple $_.ItemArray }))
Add ';'
Add

# Services keep their ids: Modules.ServiceId points at them. A service is inactive when every module using it is.
Add 'SET IDENTITY_INSERT [Services] ON;'
Add 'INSERT INTO [Services] ([Id], [ServiceName], [ServiceDescription], [Price], [IsActive]) VALUES'
Add (Join-Rows ($services | ForEach-Object {
    $svc = $_
    $users = @($modules | Where-Object { -not ($_.ServiceId -is [System.DBNull]) -and [int]$_.ServiceId -eq [int]$svc.Id })
    $active = [bool]($users | Where-Object { $inactiveModules -notcontains [int]$_.Id })
    Tuple @([int]$svc.Id, $svc.ServiceName, $svc.ServiceDescription, 0, $active)
}))
Add ';'
Add 'SET IDENTITY_INSERT [Services] OFF;'
Add

Add 'INSERT INTO [Modules] ([Id], [ModuleTypeId], [ModuleName], [HasView], [HasCreate], [HasEdit], [HasDelete], [HasSearch], [HasPrint], [HasShowList], [HasSetDefaults], [Icon], [SortOrder], [IsActive], [ServiceId]) VALUES'
Add (Join-Rows ($modules | ForEach-Object {
    $v = @($_.ItemArray)
    if ($inactiveModules -contains [int]$v[0]) { $v[13] = $false }
    Tuple $v
}))
Add ';'
Add

Add 'INSERT INTO [ModuleDefaults] ([ModuleId], [Defaults], [IsActive]) VALUES'
Add (Join-Rows ($defaults | ForEach-Object { Tuple @($_.ModuleId, $_.Defaults, $true) }))
Add ';'
Add

Add 'INSERT INTO [LookupValues] ([ModuleId], [Kind], [FieldName], [Title], [Value], [IsActive]) VALUES'
Add (Join-Rows ($lookups | ForEach-Object { Tuple @($_.ModuleId, $_.Kind, $_.FieldName, $_.Title, $_.Value, $true) }))
Add ';'
Add
Add 'COMMIT;'
Add "PRINT 'Seed complete. Sign in as Admin with the temporary password; you will be asked to change it.';"

# UTF-8 with BOM so sqlcmd reads the multiplication/superscript signs in the reference ranges correctly.
$target = [System.IO.Path]::GetFullPath($Output)
[System.IO.File]::WriteAllText($target, $sb.ToString(), (New-Object System.Text.UTF8Encoding $true))
Write-Host "Wrote $target ($($types.Count) module types, $($modules.Count) modules, $($services.Count) services, $($defaults.Count) defaults, $($lookups.Count) lookups)."
